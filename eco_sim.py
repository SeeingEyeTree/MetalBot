def parse_kv(items, nested=False):
    """['line_transition.GRIDS_OPENING_MAX=12', ...] -> {'line_transition': {'GRIDS_OPENING_MAX': 12}}"""
    out = {}
    for it in items or []:
        k, _, v = it.partition("=")
        try:
            val = json.loads(v)
        except ValueError:
            val = v
        if nested:
            mod, _, key = k.partition(".")
            out.setdefault(mod, {})[key] = val
        else:
            out[k] = val
    return out


def parse_presets(items):
    """['line_transition:+T2_UP_FRONT,-NO_IDLE'] -> {'line_transition': {'add': [...], 'remove': [...]}}"""
    out = {}
    for it in items or []:
        mod, _, rest = it.partition(":")
        p = out.setdefault(mod, {"add": [], "remove": []})
        for n in rest.split(","):
            n = n.strip()
            if n.startswith("-"):
                p["remove"].append(n[1:])
            elif n:
                p["add"].append(n.lstrip("+"))
    return out


def simulate(cfg):
    """Run one game.  cfg: bot, seed, minutes, vacuum, set, presets, phys, patch, widgets.  Returns the result dict."""
    import lupa.luajit21 as L
    lua = L.LuaRuntime(unpack_returned_tuples=True)
    root = ROOT.replace("\\", "/") + "/"
    run = lua.execute(f'return dofile("{root}ecosim/runner.lua")')
    args = {
        "root": root, "bot": cfg.get("bot", DEFAULT_BOT).replace("\\", "/").rstrip("/"),
        "widgets": cfg.get("widgets") or WIDGETS, "vacuum": cfg.get("vacuum", True),
        "end_frame": int(cfg.get("minutes", 20) * 1800), "seed": cfg.get("seed", 1),
        "phys": cfg.get("phys") or {}, "set": cfg.get("set") or {}, "presets": cfg.get("presets") or {},
        "snap_every": cfg.get("snap_every", 1800), "sink": bool(cfg.get("sink")),
    }
    if cfg.get("trace"):
        args["trace"] = list(cfg["trace"])
    if cfg.get("patch"):
        args["patch"] = os.path.abspath(cfg["patch"]).replace("\\", "/")
    t0 = time.time()
    res = lua2py(run(py2lua(lua, args)))
    res["wall_secs"] = time.time() - t0
    res["cfg"] = {k: v for k, v in cfg.items() if k != "out"}
    res["summary"] = summarize(res)
    return res


def save(res, tag):
    d = os.path.join(RUNS, tag)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "run.json"), "w", encoding="utf-8") as f:
        json.dump(res, f)
    with open(os.path.join(d, "log.txt"), "w", encoding="utf-8") as f:
        for fr, line in res.get("log", []):
            f.write(f"{fr // 1800}:{(fr // 30) % 60:02d} f{fr} {line}\n")
    return d


def _job(cfg, tag):
    """Worker: simulate + save; returns (tag, summary) so the parent never holds whole runs in memory."""
    try:
        res = simulate(cfg)
    except Exception as ex:                      # a crashed run is a result too
        return tag, {"crash": repr(ex)}
    save(res, tag)
    return tag, res["summary"]


def run_many(jobs, workers):
    """jobs: [(cfg, tag)].  Runs them in parallel processes; yields (tag, summary) as they finish."""
    workers = max(1, min(workers, len(jobs)))
    if workers == 1:
        for cfg, tag in jobs:
            yield _job(cfg, tag)
        return
    with ProcessPoolExecutor(max_workers=workers) as ex:
        futs = [ex.submit(_job, cfg, tag) for cfg, tag in jobs]
        for f in as_completed(futs):
            yield f.result()


def parse_seeds(s):
    out = []
    for part in str(s).split(","):
        if "-" in part:
            a, b = part.split("-")
            out += list(range(int(a), int(b) + 1))
        elif part:
            out.append(int(part))
    return out


def cfg_from_args(a):
    cfg = {"bot": a.bot, "minutes": a.minutes, "vacuum": not a.no_vacuum,
           "set": parse_kv(a.set, nested=True), "presets": parse_presets(a.preset), "phys": parse_kv(a.phys),
           "patch": a.patch, "trace": a.trace, "sink": a.sink}
    if a.no_unit_controller:
        cfg["widgets"] = WIDGETS[:2]
    return cfg


def cmd_run(a):
    base = cfg_from_args(a)
    seeds = parse_seeds(a.seeds) if a.seeds else [a.seed]
    if len(seeds) == 1:
        cfg = dict(base, seed=seeds[0])
        res = simulate(cfg)
        d = save(res, a.tag)
        print_summary(res)
        print(f"saved {d}")
        return
    jobs = [(dict(base, seed=s), f"{a.tag}/s{s}") for s in seeds]
    sums = {}
    t0 = time.time()
    for tag, s in run_many(jobs, a.jobs):
        sums[tag] = s
        print(f"  {tag}: " + (s.get("crash") or "  ".join(f"{m}:{s.get(f'inc{m}', '-')}" for m in (8, 10, 12, 14, 16, 18, 20))
                                 + f"  err {s.get('errors')}  wall {s.get('wall')}s"), flush=True)
    print_group(a.tag, list(sums.values()))
    print(f"{len(jobs)} runs in {time.time() - t0:.0f}s wall")


def cmd_sweep(a):
    """Many variants x seeds in parallel.  Spec (JSON):
        {"tag": "gate1", "seeds": "1-4", "minutes": 20, "base": {"bot": "candidates/STANCE_BOT", "set": {...}, "phys": {...}},
         "variants": {"base": {}, "open12": {"set": {"line_transition": {"GRIDS_OPENING_MAX": 12}}},
                      "noIdle": {"presets": {"line_transition": {"remove": ["NO_IDLE"]}}}}}
    A variant's set/phys/presets are merged over the base.  Results: ecosim/runs/<tag>/<variant>/s<N>/ and
    ecosim/runs/<tag>/sweep.json (summaries); the table ranks variants by median 20:00 income."""
    spec = json.load(open(a.spec, encoding="utf-8"))
    tag = a.tag or spec.get("tag") or os.path.splitext(os.path.basename(a.spec))[0]
    seeds = parse_seeds(a.seeds or spec.get("seeds", "1-4"))
    base = dict(spec.get("base") or {})
    base.setdefault("bot", DEFAULT_BOT)
    base.setdefault("minutes", spec.get("minutes", 20))
    if spec.get("sink"):
        base["sink"] = True
    rank_key = a.rank or spec.get("rank", "inc20")
    jobs = []
    for vname, v in (spec.get("variants") or {"base": {}}).items():
        cfg = json.loads(json.dumps(base))
        for mod, kv in (v.get("set") or {}).items():
            cfg.setdefault("set", {}).setdefault(mod, {}).update(kv)
        for mod, kv in (v.get("presets") or {}).items():
            cfg.setdefault("presets", {})[mod] = kv
        cfg.setdefault("phys", {}).update(v.get("phys") or {})
        for k in ("bot", "patch", "widgets", "vacuum", "minutes", "sink"):
            if k in v:
                cfg[k] = v[k]
        for s in seeds:
            jobs.append((dict(cfg, seed=s), f"{tag}/{vname}/s{s}"))
    print(f"sweep {tag}: {len(jobs)} runs ({len(jobs) // len(seeds)} variants x {len(seeds)} seeds), {a.jobs} at a time")
    t0 = time.time()
    by = {}
    for jt, s in run_many(jobs, a.jobs):
        v = jt.split("/")[1]
        by.setdefault(v, []).append(s)
        if a.verbose:
            print(f"  {jt}: {s.get('crash') or s.get('inc20')}", flush=True)
    rank = []
    for v, sums in by.items():
        ok = [s for s in sums if "crash" not in s]
        low = rank_key.startswith("dbl_")          # doubling time: lower is better (a run that never doubled ranks last)
        vals = [s.get(rank_key) or (99 if low else 0) for s in ok]
        med = statistics.median(vals) if vals else (99 if low else 0)
        rank.append((-med if low else med, v, sums))
    rank.sort(reverse=True)
    reals = [real_minutes(p) for p in sorted(glob.glob(a.calibrate))] if a.calibrate else None
    sinky = any("dragon20" in s for _, _, sums in rank for s in sums)
    print(f"\nranked by median {rank_key}")
    print(f"{'variant':24s} {'n':>2} {'inc20 med [range]':>22} " + " ".join(f"{m:>6}" for m in (8, 10, 12, 14, 16, 18))
          + "   t1600  t3200  " + " ".join(f"{'dbl' + str(lo) + '-' + str(hi):>8}" for lo, hi in DBL_WINDOWS) + "  errs" + ("  calib" if reals else "") + (f"   {rank_key if rank_key.startswith('dragon') else 'dragon20'}k [range]  blocks  first" if sinky else ""))
    out = {}
    for med, v, sums in rank:
        ok = [s for s in sums if "crash" not in s]
        cols = []
        for m in (8, 10, 12, 14, 16, 18):
            vals = [s.get(f"inc{m}") for s in ok if s.get(f"inc{m}") is not None]
            cols.append(f"{statistics.median(vals):6.0f}" if vals else "     -")
        i20 = [s.get("inc20", 0) for s in ok]
        t16 = [s["t1600"] for s in ok if s.get("t1600")]
        t32 = [s["t3200"] for s in ok if s.get("t3200")]
        mi20 = statistics.median(i20) if i20 else 0
        line = (f"{v:24s} {len(ok):2d} {mi20:7.0f} [{min(i20) if i20 else 0:5.0f}-{max(i20) if i20 else 0:5.0f}] " + " ".join(cols)
                + f"  {statistics.median(t16) if t16 else float('nan'):5.2f}  {statistics.median(t32) if t32 else float('nan'):5.2f}"
                + "".join(f"  {statistics.median(d) if d else float('nan'):7.2f}" for d in
                          ([s[f"dbl_{lo}_{hi}"] for s in ok if s.get(f"dbl_{lo}_{hi}")] for lo, hi in DBL_WINDOWS))
                + f"  {sum(s.get('errors', 0) for s in ok) + len(sums) - len(ok):4d}")
        if sinky:
            dk = [s.get(rank_key if rank_key.startswith("dragon") else "dragon20", 0) / 1000 for s in ok]
            bl = [s.get("blocks20", 0) for s in ok]
            fi = [s["sink_first"] for s in ok if s.get("sink_first")]
            line += (f"   {statistics.median(dk):6.0f} [{min(dk):4.0f}-{max(dk):4.0f}]  {statistics.median(bl):5.1f}"
                     f"  {statistics.median(fi) if fi else float('nan'):5.2f}")
        if reals:
            sims = [sim_minutes(json.load(open(os.path.join(RUNS, tag, v, f"s{s}", "run.json"), encoding="utf-8"))) for s in seeds]
            sc, _ = calib_score(reals, sims)
            line += f"  {sc:.3f}"
        print(line)
        out[v] = sums
    os.makedirs(os.path.join(RUNS, tag), exist_ok=True)
    json.dump({"spec": spec, "seeds": seeds, "results": out}, open(os.path.join(RUNS, tag, "sweep.json"), "w"))
    print(f"\n{len(jobs)} runs in {time.time() - t0:.0f}s wall -> {os.path.join(RUNS, tag)}")


def print_group(name, sums):
    """Median and range over seeds."""
    ok = [s for s in sums if "crash" not in s]
    parts = []
    for m in (8, 10, 12, 14, 16, 18, 20):
        v = [s[f"inc{m}"] for s in ok if f"inc{m}" in s]
        if v:
            parts.append(f"{m}:{statistics.median(v):.0f} [{min(v)}-{max(v)}]")
    for lo, hi in DBL_WINDOWS:
        v = [s[f"dbl_{lo}_{hi}"] for s in ok if s.get(f"dbl_{lo}_{hi}")]
        if v:
            parts.append(f"dbl{lo}-{hi}:{statistics.median(v):.2f}")
    print(f"{name}: n={len(ok)} " + "  ".join(parts))


# ── summaries ────────────────────────────────────────────────────────────────

MILESTONES = (200, 400, 800, 1600, 3200, 6400)
DBL_WINDOWS = ((6, 12), (10, 16), (14, 20))     # minutes: income doubling time fitted over each window (dbl_<a>_<b>)


def fit_doubling(tl, lo, hi):
    """minutes per doubling of metal income over [lo, hi] game-minutes: log-linear least squares of the 10 s samples
    (eco_scaling.fit_doubling on the sim timeline).  None when income does not grow."""
    xs = [(r["frame"] / 1800, math.log(r["mi"])) for r in tl if lo * 1800 <= r["frame"] <= hi * 1800 and r["mi"] > 1]
    if len(xs) < 4:
        return None
    n = len(xs)
    mx = sum(x for x, _ in xs) / n
    my = sum(y for _, y in xs) / n
    sxx = sum((x - mx) ** 2 for x, _ in xs)
    sxy = sum((x - mx) * (y - my) for x, y in xs)
    if sxx <= 0 or sxy <= 0:
        return None
    return math.log(2) / (sxy / sxx)


def avg_income(tl, frame, window=900):
    """metal income averaged over the window ending at `frame` (like the tracker's *_avg)."""
    rows = [r for r in tl if frame - window < r["frame"] <= frame]
    return statistics.mean(r["mi"] for r in rows) if rows else None


def summarize(res):
    tl = res.get("timeline") or []
    s = {"errors": len(res.get("errors") or []), "wall": round(res.get("wall_secs", 0), 1)}
    for m in (6, 8, 10, 12, 14, 16, 18, 20, 22, 25, 30):
        v = avg_income(tl, m * 1800)
        if v is not None:
            s[f"inc{m}"] = round(v)
    for x in MILESTONES:
        hit = next((r["frame"] for r in tl if r["mi"] >= x), None)
        s[f"t{x}"] = round(hit / 1800, 2) if hit else None
    for lo, hi in DBL_WINDOWS:
        d = fit_doubling(tl, lo, hi)
        s[f"dbl_{lo}_{hi}"] = round(d, 2) if d else None
    if tl and "dragon_m" in tl[-1]:
        at20 = next((r for r in tl if r["frame"] == 36000), tl[-1])
        s["dragon20"] = round(at20.get("dragon_m", 0))          # metal into Dragons by 20:00
        s["dragons20"] = at20.get("dragons", 0)
        s["blocks20"] = at20.get("sink_blocks", 0)
        first = next((r["frame"] for r in tl if r.get("sink_blocks", 0) > 0), None)
        s["sink_first"] = round(first / 1800, 2) if first else None
        s["dragon_end"] = round(tl[-1].get("dragon_m", 0))     # metal into Dragons by the end of the run
        for m in (22, 25, 30):
            r = next((x for x in tl if x["frame"] == m * 1800), None)
            if r:
                s[f"dragon{m}"] = round(r.get("dragon_m", 0))
    if tl:
        last = tl[-1]
        s["mprod"] = round(last["mprod"])
        s["mused"] = round(last["mused"])
        s["mwaste"] = round(last["mwaste"])
        s["bank_end"] = round(last["m"])
        s["units_end"] = last["units"]
    return s


def print_summary(res):
    s = res["summary"]
    inc = "  ".join(f"{m}:{s.get(f'inc{m}', '-')}" for m in (6, 8, 10, 12, 14, 16, 18, 20))
    ms = "  ".join(f"{x}@{s.get(f't{x}') or '-'}" for x in MILESTONES)
    print(f"income (avg m/s at minute)  {inc}")
    print(f"time to m/s (min)           {ms}")
    print("doubling time (min)         " + "  ".join(f"{lo}-{hi}:{s.get(f'dbl_{lo}_{hi}') or '-'}" for lo, hi in DBL_WINDOWS))
    print(f"metal produced {s.get('mprod')}  used {s.get('mused')}  wasted {s.get('mwaste')}  bank at end {s.get('bank_end')}"
          f"  units {s.get('units_end')}")
    if "dragon20" in s:
        print(f"army sink: {s['blocks20']} Dragon blocks by 20:00 (first at {s['sink_first']} min), {s['dragon20']} metal into Dragons"
              f" ({s['dragons20']} Dragons)")
    p = res.get("prof", {})
    print(f"wall {res.get('wall_secs', 0):.1f}s (bot callins {p.get('callin', 0):.1f}s, physics {p.get('step', 0):.1f}s)"
          f"  orders {p.get('orders_given')}  Lua errors {s['errors']}  missing API: {', '.join(res.get('missing') or []) or '-'}")
    sc = p.get("scans")
    if sc:
        print("unit-list scans            " + "  ".join("%s %d calls / %.1fM entries" % (k, v[0], v[1] / 1e6) for k, v in sorted(sc.items())))
    for e in (res.get("errors") or [])[:3]:
        print("  ERROR", e.get("frame"), e.get("widget"), e.get("callin"), str(e.get("err"))[:400])


