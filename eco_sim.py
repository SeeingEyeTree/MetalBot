def _runs(path):
    """A run.json, a run dir, or a variant dir with s*/run.json (seeds) -> list of runs."""
    if os.path.isfile(path):
        return [json.load(open(path, encoding="utf-8"))]
    files = sorted(glob.glob(os.path.join(path, "s*", "run.json"))) or sorted(glob.glob(os.path.join(path, "run.json")))
    return [json.load(open(p, encoding="utf-8")) for p in files]


def _window_stats(runs, f0, f1):
    """Medians over seeds of window averages and end-of-window counts / ledger / spend."""
    rows = []
    for r in runs:
        tl = r["timeline"]
        win = [x for x in tl if f0 < x["frame"] <= f1]
        a = next((x for x in tl if x["frame"] == f0), None)
        b = next((x for x in tl if x["frame"] == f1), None)
        if not win or not b:
            continue
        g = group_ledger(ledger_window(a, b))
        tot = sum(g.values()) or 1
        sp_a, sp_b = (a or {}).get("spent") or {}, b.get("spent") or {}
        rows.append({
            "m_inc": statistics.mean(x["mi"] for x in win), "m_use": statistics.mean(x["mx"] for x in win),
            "e_inc": statistics.mean(x["ei"] for x in win), "m_bank": b["m"], "e_bank%": 100 * b["e"] / max(b["es"], 1),
            **{"n_" + k: b["fin"].get(k, 0) for k in ("mex", "moho", "wind", "fusion", "nano", "con", "lab")},
            "bp_build%": 100 * g.get("build", 0) / tot, "bp_idle%": 100 * (g.get("idle", 0) + g.get("no_target", 0) + g.get("wait", 0)) / tot,
            **{"spent_" + k: (sp_b.get(k, 0) - sp_a.get(k, 0)) / ((f1 - f0) / 30) for k in set(sp_b) | set(sp_a)},
        })
    if not rows:
        return {}
    keys = set().union(*rows)
    return {k: statistics.median(r.get(k, 0) for r in rows) for k in keys}


def cmd_compare(a):
    A, B = _runs(a.a), _runs(a.b)
    print(f"A = {a.a} ({len(A)} runs)   B = {a.b} ({len(B)} runs)   values are medians over runs; spent_* = metal/s by what was built")
    step = int(a.window * 1800)
    keys = ["m_inc", "m_use", "e_inc", "m_bank", "e_bank%", "n_mex", "n_moho", "n_wind", "n_fusion", "n_nano", "n_con", "n_lab",
            "bp_build%", "bp_idle%"]
    windows = list(range(step, int(max(r["timeline"][-1]["frame"] for r in A + B)) + 1, step))
    stats = [(f1, _window_stats(A, f1 - step, f1), _window_stats(B, f1 - step, f1)) for f1 in windows]
    spend = sorted({k for _, sa, sb in stats for k in list(sa) + list(sb) if k.startswith("spent_")})
    print(f"{'':10s}" + "".join(f"{clock(f1):>14s}" for f1, _, _ in stats))
    for k in keys + spend:
        line = f"{k:10s}"
        for _, sa, sb in stats:
            va, vb = sa.get(k, 0), sb.get(k, 0)
            line += f"{va:6.0f}>{vb:<7.0f}"
        print(line)
    sa = [r["summary"].get("inc20") for r in A if r["summary"].get("inc20")]
    sb = [r["summary"].get("inc20") for r in B if r["summary"].get("inc20")]
    if sa and sb:
        print(f"\n20:00 income: A {statistics.median(sa):.0f}  B {statistics.median(sb):.0f}  (x{statistics.median(sb) / statistics.median(sa):.2f})")
    for lo, hi in DBL_WINDOWS:          # recomputed from the timeline, so runs saved before the metric existed compare too
        da = [d for d in (fit_doubling(r["timeline"], lo, hi) for r in A) if d]
        db = [d for d in (fit_doubling(r["timeline"], lo, hi) for r in B) if d]
        if da and db:
            print(f"doubling time {lo}-{hi} min: A {statistics.median(da):.2f}  B {statistics.median(db):.2f} min")


