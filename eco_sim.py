LEDGER_GROUPS = {"build": "build", "reclaim": "reclaim", "travel": "travel", "idle": "idle", "stall_m": "stall_m",
                 "stall_e": "stall_e", "fight_idle": "no_target", "guard_idle": "no_target", "overbuild": "overbuild",
                 "off": "off", "cap": "cap", "move": "travel"}


def ledger_window(a, b):
    """BP-seconds per builder class and state between two timeline rows (cumulative ledgers)."""
    out = {}
    for cls, t in (b.get("ledger") or {}).items():
        prev = (a.get("ledger") or {}).get(cls, {}) if a else {}
        for k, v in t.items():
            d = v - prev.get(k, 0)
            if d:
                out.setdefault(cls, {})[k] = d
    return out


def group_ledger(lw, classes=None):
    g = {}
    for cls, t in lw.items():
        if classes and cls not in classes:
            continue
        for k, v in t.items():
            key = "build" if k.startswith("build:") else LEDGER_GROUPS.get(k, "wait")
            g[key] = g.get(key, 0) + v
    return g


def bottleneck(row, g, prev):
    tot = sum(g.values()) or 1
    share = {k: v / tot for k, v in g.items()}
    mfrac = row["m"] / max(row["ms"], 1)
    efrac = row["e"] / max(row["es"], 1)
    if share.get("stall_e", 0) > 0.15 and efrac < 0.2:
        return "ENERGY (builders held back for energy)"
    if share.get("stall_m", 0) > 0.15 and mfrac < 0.2:
        return "METAL (builders held back for metal)"
    if mfrac > 0.5 and efrac > 0.5:
        idle = share.get("idle", 0) + share.get("no_target", 0) + share.get("wait", 0)
        trav = share.get("travel", 0)
        return "WORK/BP (banks float: %d%% idle, %d%% travel)" % (100 * idle, 100 * trav)
    if mfrac > 0.5:
        return "metal floats, energy short" if share.get("stall_e", 0) > 0.05 else "metal floats (BP short)"
    if efrac > 0.7:
        return "metal-bound (energy floats)"
    return "balanced"


def grid_table(res):
    """One row per grid: open time/reason from the [LT] log, build progress from the sim's finished-unit events."""
    import re
    grids = []
    for fr, line in res.get("log", []):
        m = re.search(r"grid cell \((\-?\d+), (\-?\d+)\) opened \((\w[\w-]*)", line) or \
            re.search(r"first grid cell \((\-?\d+), (\-?\d+)\)()", line)
        if m:
            grids.append({"x": int(m.group(1)), "z": int(m.group(2)), "open": fr, "why": m.group(3) or "first"})
    ev = [e for e in (res.get("events") or []) if e.get("kind") == "finished"]
    for g in grids:
        inside = [e for e in ev if abs(e["x"] - g["x"]) <= 232 and abs(e["z"] - g["z"]) <= 232 and e["frame"] >= g["open"]]
        g["n"] = {}
        for e in inside:
            g["n"][e["cat"]] = g["n"].get(e["cat"], 0) + 1
        t1 = [e for e in inside if e["cat"] in ("mex", "wind", "nano")]
        g["first"] = min((e["born"] for e in t1), default=None)
        g["t1_done"] = max((e["frame"] for e in t1), default=None)
        nanos = sorted(e["frame"] for e in inside if e["cat"] == "nano")
        g["nano7"] = nanos[6] if len(nanos) >= 7 else None
        moho = sorted(e["frame"] for e in inside if e["cat"] == "moho")
        g["moho_first"], g["moho_last"] = (moho[0], moho[-1]) if moho else (None, None)
    return grids


def clock(fr):
    return "-" if fr is None else f"{fr // 1800}:{(fr // 30) % 60:02d}"


