# ── Lua helpers ──────────────────────────────────────────────────────────────

def lua_literal(v, ind=0):
    """Python value -> Lua table constructor source."""
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        if isinstance(v, float) and (math.isnan(v) or math.isinf(v)):
            return "0"
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)          # JSON string escapes are valid Lua
    if isinstance(v, (list, tuple)):
        return "{" + ",".join(lua_literal(x, ind) for x in v) + "}"
    if isinstance(v, dict):
        parts = []
        for k, x in v.items():
            if isinstance(k, int):
                key = f"[{k}]"
            elif isinstance(k, str) and k.isidentifier() and k not in LUA_KEYWORDS:
                key = k
            else:
                key = "[" + json.dumps(str(k)) + "]"
            parts.append(f"{key}={lua_literal(x, ind)}")
        return "{" + ",".join(parts) + "}"
    return "nil"


LUA_KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil",
                "not", "or", "repeat", "return", "then", "true", "until", "while", "goto"}


def lua2py(v):
    """lupa table -> Python (arrays for 1..n keys)."""
    from lupa.luajit21 import lua_type
    if lua_type(v) == "table":
        keys = list(v.keys())
        if keys and all(isinstance(k, int) for k in keys) and sorted(keys) == list(range(1, len(keys) + 1)):
            return [lua2py(v[k]) for k in range(1, len(keys) + 1)]
        return {(k if isinstance(k, (int, str)) else str(k)): lua2py(x) for k, x in v.items()}
    if isinstance(v, bytes):
        return v.decode("utf-8", "replace")
    return v


def py2lua(lua, v):
    if isinstance(v, dict):
        t = lua.table()
        for k, x in v.items():
            if isinstance(k, str) and k.lstrip("-").isdigit():
                k = int(k)                      # JSON object keys are strings; Lua tables like SILO_GRIDS index by number
            t[k] = py2lua(lua, x)
        return t
    if isinstance(v, (list, tuple)):
        t = lua.table()
        for i, x in enumerate(v, 1):
            t[i] = py2lua(lua, x)
        return t
    return v


