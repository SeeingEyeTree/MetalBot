def cmd_defs(a):
    """Engine UnitDefs/WeaponDefs dump (metalbot_state_dump.lua [UDEF]/[UWDEF] rows in a result json) -> ecosim/unitdefs.lua."""
    d = json.load(open(a.result, encoding="utf-8"))
    sd = d.get("state_dump", {}).get("0") or {}
    defs, wdefs, mp = sd.get("defs") or {}, sd.get("weapon_defs") or {}, sd.get("map") or {}
    if not defs:
        sys.exit("no [UDEF] rows in that result (run a game with metalbot_state_dump.lua installed)")
    units = []
    for name, x in sorted(defs.items()):
        x = dict(x)
        x["weapons"] = [{k: v for k, v in (w or {}).items() if v is not None} for w in (x.get("weapons") or [])]
        x["buildOptions"] = list(x.get("buildOptions") or [])
        x["customParams"] = {str(k): (v if isinstance(v, (str, int, float, bool)) else json.dumps(v))
                             for k, v in (x.get("customParams") or {}).items()}
        units.append(x)
    weapons = {int(k): v for k, v in wdefs.items()}
    out = os.path.join(ROOT, "ecosim", "unitdefs.lua")
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- generated by eco_sim.py defs from %s (engine %s) -- do not edit\n" %
                (os.path.basename(a.result), mp.get("gameVersion", "?")))
        f.write("return {\nmap = " + lua_literal(mp) + ",\nunits = {\n")
        for u in units:
            f.write(lua_literal(u) + ",\n")
        f.write("},\nweapons = " + lua_literal(weapons) + "\n}\n")
    print(f"wrote {len(units)} unit defs, {len(weapons)} weapon defs -> {out}")


